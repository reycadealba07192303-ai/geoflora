"""Write GeoFlora's species information module (apps/web/src/features/identification/species-information.ts) from
metadata/species_descriptions.json and the species catalog, keyed by the GeoFlora class ids of a packaged candidate.

  python scripts/export_species_information.py --candidate ../storage/models/candidates/geoflora-mnv2-21cls-v1 \
      --out ../apps/web/src/features/identification/species-information.ts
"""

import json
from pathlib import Path

from _common import parser, setup

NISSAP_URL = "https://www.philchm.ph/wp-content/uploads/2024/01/NISSAP-2020-2030.pdf"
STATUS_TEXT = {
    "target_invasive": "Target invasive species in the Philippines (DENR-BMB NISSAP 2020-2030)",
    "introduced_naturalized": "Introduced or naturalized; not a GeoFlora target",
    "native_nontarget": "Native; not a GeoFlora target",
    "unresolved": "Not a GeoFlora target species; ecological status in the Philippines unresolved",
}

HEADER = """// GENERATED by ml-lab/scripts/export_species_information.py from ml-lab/metadata/species_descriptions.json and the
// species catalog. Edit those sources and re-run the script instead of editing this file.
// Reference information about each species the live model can suggest, independent of the model's confidence in a photo.
// Descriptions are drafts until review_status is "reviewed".

export interface SpeciesInformation {
  description: string;
  appearance: string;
  impact: string;
  source: { label: string; url: string };
  commonNames?: string[];
  family?: string;
  nativeRange?: string;
  features?: string[];
  lookalikes?: { name: string; howToTell: string }[];
  ecologicalStatus?: "target_invasive" | "introduced_naturalized" | "native_nontarget" | "unresolved";
  statusText?: string;
  references?: string[];
  reviewStatus?: string;
}

export const speciesInformation: Readonly<Record<string, SpeciesInformation>> = """


def main():
    p = parser(__doc__)
    p.add_argument("--candidate", required=True, help="packaged GeoFlora candidate directory")
    p.add_argument("--out", required=True)
    args = p.parse_args()
    cfg = setup(args)
    from geoflora_ml.catalog import by_id, load_catalog
    from geoflora_ml.config import project_path
    from geoflora_ml.utils import read_json

    cand = Path(args.candidate)
    classes = read_json(cand / "evaluation.json")["classes"]
    desc = read_json(project_path(cfg, "species_descriptions"))
    catalog = by_id(load_catalog(project_path(cfg, "species_catalog")))
    info = {}
    for c in classes:
        d, sp = desc.get(c["lab_species_id"]), catalog[c["lab_species_id"]]
        if d is None:
            raise SystemExit(f"no description for {c['scientific_name']}")
        target = sp.ecological_status == "target_invasive"
        refs = d.get("references", [])
        source = ({"label": "DENR-BMB · National Invasive Species Strategy and Action Plan 2020-2030", "url": NISSAP_URL}
                  if target else {"label": "GBIF species page", "url": next((r.split(": ", 1)[1] for r in refs if "gbif.org" in r),
                                                                         f"https://www.gbif.org/species/{sp.gbif_taxon_key}")})
        info[c["id"]] = {
            "description": d["summary"],
            "appearance": " ".join(d.get("identifying_features", [])),
            "impact": d.get("why_it_matters", ""),
            "source": source,
            "commonNames": d.get("common_names", []),
            "family": d.get("family", ""),
            "nativeRange": d.get("native_range", ""),
            "features": d.get("identifying_features", []),
            "lookalikes": [{"name": l["scientific_name"], "howToTell": l["how_to_tell_apart"]} for l in d.get("lookalikes", [])],
            "ecologicalStatus": sp.ecological_status,
            "statusText": STATUS_TEXT[sp.ecological_status],
            "references": refs,
            "reviewStatus": d.get("review_status", "draft_unverified"),
        }
    Path(args.out).write_text(HEADER + json.dumps(info, indent=2, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {len(info)} species to {args.out}")


if __name__ == "__main__":
    main()
